export function messageFor(key: string | undefined | null): string {
  if (!key) return catalog["ui.generic.error"];
  return catalog[key] ?? `Something went wrong (${key}).`;
}

export function errorText(error: unknown): string {
  if (error && typeof error === "object" && "messageKey" in error) {
    return messageFor((error as { messageKey: string }).messageKey);
  }
  if (error instanceof Error) return error.message;
  return catalog["ui.generic.error"];
}
